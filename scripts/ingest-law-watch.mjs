#!/usr/bin/env node
/**
 * Merge reviewed law-watch drafts into data/research-bank.jsonl.
 * Never replaces the research bank. Never invents rows.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { isResearchShape, parseJsonl } from "./research-normalize.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_WATCH = join(root, "data/law-watch/latest.jsonl");
const RESEARCH = join(root, "data/research-bank.jsonl");
const META = join(root, "data/law-watch/meta.json");
const SNAPSHOT = join(root, "lib/law-watch-meta.ts");

function fail(message) {
  throw new Error(message);
}

function readMeta(metaPath) {
  if (!existsSync(metaPath)) {
    return { lastIngest: null, updatedAt: new Date().toISOString().slice(0, 10), status: "scaffold" };
  }
  return JSON.parse(readFileSync(metaPath, "utf8"));
}

export function writeClientSnapshot(meta, snapshotPath = SNAPSHOT) {
  const status = meta.status === "merged" || meta.status === "draft" ? meta.status : "scaffold";
  const last = meta.lastIngest ? JSON.stringify(meta.lastIngest) : "null";
  writeFileSync(
    snapshotPath,
    `/** Generated by scripts/ingest-law-watch.mjs — do not invent values by hand. */\nexport const LAW_WATCH_META = {\n  lastIngest: ${last} as string | null,\n  updatedAt: ${JSON.stringify(meta.updatedAt)},\n  status: ${JSON.stringify(status)} as "scaffold" | "draft" | "merged",\n  cadenceDays: ${Number(meta.cadenceDays) || 2},\n};\n`,
  );
}

export function ingestLawWatch(watchPath = DEFAULT_WATCH, options = {}) {
  const researchPath = options.research || RESEARCH;
  const metaPath = options.meta || META;
  const snapshotPath = options.snapshot || SNAPSHOT;
  const from = resolve(watchPath);
  if (!existsSync(from)) fail(`law-watch file not found: ${from}`);
  if (!existsSync(researchPath)) fail(`research bank missing: ${researchPath}`);

  const incoming = parseJsonl(readFileSync(from, "utf8"));
  if (incoming.issues.length) fail(`law-watch JSONL issues: ${incoming.issues.join("; ")}`);

  const existingRaw = readFileSync(researchPath, "utf8");
  const existing = parseJsonl(existingRaw);
  if (existing.issues.length) fail(`research JSONL issues: ${existing.issues.join("; ")}`);

  const ids = new Set(existing.records.map((row) => row.id).filter(Boolean));
  const additions = [];
  for (const row of incoming.records) {
    if (!row?.id || ids.has(row.id)) continue;
    if (!isResearchShape(row)) {
      fail(`law-watch row ${row.id} is not research-shaped — refused`);
    }
    additions.push(row);
    ids.add(row.id);
  }

  const today = new Date().toISOString().slice(0, 10);
  const meta = {
    ...readMeta(metaPath),
    updatedAt: today,
  };

  if (!additions.length) {
    writeFileSync(metaPath, `${JSON.stringify(meta, null, 2)}\n`);
    writeClientSnapshot(meta, snapshotPath);
    console.log(`law-watch: 0 new rows from ${from} (research-bank unchanged)`);
    return { added: 0, meta };
  }

  const chunk = additions.map((row) => JSON.stringify(row)).join("\n");
  const prefix = existingRaw.endsWith("\n") || !existingRaw ? "" : "\n";
  writeFileSync(researchPath, `${existingRaw}${prefix}${chunk}\n`);
  meta.lastIngest = today;
  meta.status = "merged";
  writeFileSync(metaPath, `${JSON.stringify(meta, null, 2)}\n`);
  writeClientSnapshot(meta, snapshotPath);
  console.log(`law-watch: merged ${additions.length} new id(s) → research bank`);
  return { added: additions.length, meta };
}

function main() {
  const arg = process.argv[2];
  try {
    ingestLawWatch(arg && !arg.startsWith("-") ? arg : DEFAULT_WATCH);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
